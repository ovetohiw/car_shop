CREATE TABLE users (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         VARCHAR2(255) NOT NULL,
  password_hash VARCHAR2(100) NOT NULL,
  role          VARCHAR2(32)  NOT NULL,
  created_at    TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT uk_users_email UNIQUE (email),
  CONSTRAINT ck_users_role CHECK (role IN ('CUSTOMER', 'STAFF'))
);

CREATE TABLE car_models (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        VARCHAR2(64)   NOT NULL,
  name        VARCHAR2(255)  NOT NULL,
  description VARCHAR2(1000),
  base_price  NUMBER(12, 2)  NOT NULL,
  image_url   VARCHAR2(512)  NOT NULL,
  CONSTRAINT uk_car_models_code UNIQUE (code),
  CONSTRAINT ck_car_models_base_price CHECK (base_price >= 0)
);

CREATE TABLE trims (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  car_model_id NUMBER        NOT NULL,
  code         VARCHAR2(64)  NOT NULL,
  name         VARCHAR2(255) NOT NULL,
  price_delta  NUMBER(12, 2) DEFAULT 0 NOT NULL,
  CONSTRAINT fk_trims_car_model FOREIGN KEY (car_model_id) REFERENCES car_models (id),
  CONSTRAINT uk_trims_model_code UNIQUE (car_model_id, code),
  CONSTRAINT ck_trims_price_delta CHECK (price_delta >= 0)
);

CREATE TABLE colors (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        VARCHAR2(64)  NOT NULL,
  name        VARCHAR2(255) NOT NULL,
  hex_code    VARCHAR2(7)   NOT NULL,
  price_delta NUMBER(12, 2) DEFAULT 0 NOT NULL,
  CONSTRAINT uk_colors_code UNIQUE (code),
  CONSTRAINT ck_colors_price_delta CHECK (price_delta >= 0)
);

CREATE TABLE extra_services (
  id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code  VARCHAR2(64)  NOT NULL,
  name  VARCHAR2(255) NOT NULL,
  price NUMBER(12, 2) NOT NULL,
  CONSTRAINT uk_extra_services_code UNIQUE (code),
  CONSTRAINT ck_extra_services_price CHECK (price >= 0)
);

CREATE TABLE parts (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku         VARCHAR2(64)  NOT NULL,
  name        VARCHAR2(255) NOT NULL,
  description VARCHAR2(1000),
  price       NUMBER(12, 2) NOT NULL,
  image_url   VARCHAR2(512) NOT NULL,
  stock_qty   NUMBER(10)    DEFAULT 0 NOT NULL,
  CONSTRAINT uk_parts_sku UNIQUE (sku),
  CONSTRAINT ck_parts_price CHECK (price >= 0),
  CONSTRAINT ck_parts_stock CHECK (stock_qty >= 0)
);

CREATE TABLE orders (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      NUMBER         NOT NULL,
  status       VARCHAR2(32)   NOT NULL,
  total_amount NUMBER(12, 2)  NOT NULL,
  created_at   TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,
  updated_at   TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users (id),
  CONSTRAINT ck_orders_status CHECK (status IN (
    'NEW', 'SUBMITTED', 'IN_FULFILLMENT', 'COMPLETED', 'CANCELLED'
  )),
  CONSTRAINT ck_orders_total CHECK (total_amount >= 0)
);

CREATE TABLE order_items (
  id                   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id             NUMBER         NOT NULL,
  item_type            VARCHAR2(16)   NOT NULL,
  car_model_id         NUMBER,
  trim_id              NUMBER,
  color_id             NUMBER,
  part_id              NUMBER,
  quantity             NUMBER(10)     DEFAULT 1 NOT NULL,
  unit_price           NUMBER(12, 2)  NOT NULL,
  line_total           NUMBER(12, 2)  NOT NULL,
  description_snapshot VARCHAR2(1000) NOT NULL,
  CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id),
  CONSTRAINT fk_order_items_car_model FOREIGN KEY (car_model_id) REFERENCES car_models (id),
  CONSTRAINT fk_order_items_trim FOREIGN KEY (trim_id) REFERENCES trims (id),
  CONSTRAINT fk_order_items_color FOREIGN KEY (color_id) REFERENCES colors (id),
  CONSTRAINT fk_order_items_part FOREIGN KEY (part_id) REFERENCES parts (id),
  CONSTRAINT ck_order_items_type CHECK (item_type IN ('CAR', 'PART')),
  CONSTRAINT ck_order_items_qty CHECK (quantity > 0),
  CONSTRAINT ck_order_items_unit_price CHECK (unit_price >= 0),
  CONSTRAINT ck_order_items_line_total CHECK (line_total >= 0)
);

CREATE TABLE order_item_extras (
  order_item_id    NUMBER        NOT NULL,
  extra_service_id NUMBER        NOT NULL,
  price            NUMBER(12, 2) NOT NULL,
  CONSTRAINT pk_order_item_extras PRIMARY KEY (order_item_id, extra_service_id),
  CONSTRAINT fk_oie_item FOREIGN KEY (order_item_id) REFERENCES order_items (id),
  CONSTRAINT fk_oie_extra FOREIGN KEY (extra_service_id) REFERENCES extra_services (id),
  CONSTRAINT ck_oie_price CHECK (price >= 0)
);

CREATE INDEX idx_trims_car_model_id ON trims (car_model_id);
CREATE INDEX idx_orders_user_id ON orders (user_id);
CREATE INDEX idx_orders_status ON orders (status);
CREATE INDEX idx_order_items_order_id ON order_items (order_id);
